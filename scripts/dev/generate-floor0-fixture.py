class Bits:
    def __init__(self): self.bits=[]
    def put(self, value, count): self.bits += [(value>>i)&1 for i in range(count)]
    def data(self): return bytes(sum(self.bits[i+j]<<j for j in range(min(8,len(self.bits)-i))) for i in range(0,len(self.bits),8))

