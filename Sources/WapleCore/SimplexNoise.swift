/// Wallpaper Engine 이 **정적 링크해 쓰는 심플렉스 노이즈 커널**의 순수 Swift 이식.
///
/// 실물에는 계보가 다른 두 벌이 함께 들어 있고, 이 파일은 그 둘을 각각 옮긴다.
///
/// ## ① 2D — Stefan Gustavson `simplexnoise1234.c` 계열 (스칼라)
///
/// | 심볼 | VA |
/// |---|---|
/// | `snoise2` | `0x14027b170`–`0x14027b4ab` |
/// | `snoise1` (미이식, 참고) | `0x14027b090`–`0x14027b16b` |
/// | 1D fBm 루프 (미이식, 참고) | `0x14027b4b0`–`0x14027b656` |
/// | `perm[256]` | `0x140484f40`–`0x140485040` |
///
/// 상수도 upstream 그대로다 — `F2 = 0.366025403f`(`0x1404926a4`),
/// `G2 = 0.211324865f`(`0x140492680`), `2·G2`(`0x1404926b4`), 감쇠 `0.5`(`0x1404926c0`).
/// 인덱싱은 `perm[512]` 대신 **256바이트 표 + 8비트 랩**이다
/// (`add al, byte ptr [rcx+r11]` @`0x14027b2f4`) — 표가 256 주기로 타일링돼 있어
/// upstream 의 `perm[ii + perm[jj]]` 과 산술적으로 동일하다.
///
/// **upstream 과 갈리는 지점 두 곳** (둘 다 바이너리를 따랐다):
///
/// 1. `grad2` 의 해시 분기. upstream 은 `int h = hash & 7; u = h<4 ? x : y`, 즉 비트 2 하나만
///    본다. 실물은 `test al, 0x3C`(`0x14027b300` · `0x14027b37e` · `0x14027b408`) — 비트 2..5 를
///    통째로 본다(= `hash & 0x3F` 를 h 로 두고 `h < 4`). `hash = 8` 에서 벌써 갈린다.
///    나머지(`h&1` 로 u 부호, `h&2` 로 v 에 `-2` 또는 `+2`)는 upstream 과 같다.
/// 2. 최종 스케일이 upstream 의 `40.0f` 가 아니라 **`45.23065185546875`**(`0x1404928c8`,
///    `mulss` @`0x14027b49c`). upstream 의 40 은 실측 진폭이 ±0.884 에 그치는 과소 정규화인데,
///    45.23065… 를 쓰면 봉우리가 정확히 ±1 에 닿는다(파이썬 레퍼런스로 격자 탐색 시
///    max|snoise2| = 0.9999959). 즉 WE 가 정규화를 고쳐 넣은 것이다.
///
/// ## ② 3D — Gustavson/Eastman `SimplexNoise.java` 계열 (4-wide SIMD)
///
/// | 심볼 | VA |
/// |---|---|
/// | `snoise3` SSE2 경로 | `0x1400fc220`–`0x1400fd006` |
/// | `snoise3` SSE4.1 경로 (`roundps`/`blendvps`) | `0x1400fd010`–`0x1400fdc41` |
/// | `perm[512]` | `0x1404833a0`–`0x1404835a0` |
/// | `permMod12[512]` | `0x1404831a0`–`0x1404833a0` |
/// | `grad3` y 성분 `[12]` | `0x140483140`–`0x140483170` |
/// | `grad3` x 성분 `[12]` | `0x140483170`–`0x1404831a0` |
/// | `grad3` z 성분 `[12]` | `0x1404835a0`–`0x1404835d0` |
///
/// 상수는 `F3 = 1/3`(`0x140483610`), `G3 = 1/6`(`0x140483600`), `2·G3 = 1/3`(`0x1404835e0`),
/// `3·G3 = 0.5`(`0x140483650`), 감쇠 `0.6`(`0x140483620`), 최종 `×32.0`(`0x1404835d0`).
/// 표·기울기·상수·스케일은 upstream 과 **전부 일치**한다.
///
/// 다만 코너 선택이 다르다. 실물은 4레인 SIMD 라 자바 원본의 `if/else` 사슬을 분기 없는 마스크
/// 조합으로 펼쳐 놨는데(`0x1400fc517`–`0x1400fc6be`), **`j1` 은 `z0 < y0`(`cmpltps`
/// @`0x1400fc590`)를 쓰고 `j2` 는 `z0 <= y0`(`cmpleps` @`0x1400fc536`)를 쓴다.**
/// 그래서 `y0 == z0 && x0 < y0` 인 점에서 `(i1, j1, k1) = (0, 0, 0)` 이 나온다 — 자바 사슬은
/// 절대 그런 조합을 내지 않는다(항상 1 이 정확히 하나). 그 점에서는 코너 0 과 코너 1 이 같은
/// 격자점을 두 번 세고, 치역이 ±1 을 넘어선다(실측 최대 ±1.39, 동률 집합 위에서 약 1.2%).
/// SSE4.1 경로(`0x1400fd18d` / `0x1400fd1f2`)도 같은 술어라 두 디스패치가 일치한다 — 오타가
/// 아니라 이 빌드의 실제 동작이다. **실물을 따랐다.**
///
/// 동률은 두 좌표의 차가 정확한 정수일 때 나므로(예: `snoise3(1.55, 2.7, -2.3)`, `y - z = 5`)
/// "예쁜" 좌표에서는 드물지 않다. 호출부가 [-1, 1] 을 계약으로 삼는다면 **호출부에서 클램프**해라
/// (`ParticleSimulator.remapNoise01` 이 이미 `max(-1, min(1, n))` 을 건다).
///
/// ## 이식 범위
///
/// 비트동일은 목표가 아니고 **가능하지도 않다** — 3D 실물은 4레인 SIMD 라 덧셈 결합 순서가
/// 스칼라와 다르다(`s = ((y+z)+x)·F3` @`0x1400fc2c6`). 상수·표·분기 술어·연산 순서를 맞췄으니
/// 스칼라 부동소수 오차(~1e-7) 안에서 일치한다. `SimplexNoiseTests` 가 독립 파이썬 구현으로
/// 뽑은 값과 1e-5 로 대조한다.
public enum SimplexNoise {

    // MARK: - 공개 API

    /// 2D 심플렉스 노이즈. 치역 [-1, 1] (실측 봉우리 ±0.999996).
    /// 실물 `0x14027b170`–`0x14027b4ab` 이식.
    public static func snoise2(_ x: Float, _ y: Float) -> Float {
        let px = fold(x), py = fold(y)

        // 스큐: s = (x+y)·F2 (0x14027b1a8), i = floor(x+s), j = floor(y+s) (0x14027b1dd/0x14027b1f4)
        let s = (px + py) * f2
        let i = fastFloor(px + s)
        let j = fastFloor(py + s)

        // 언스큐: t = (i+j)·G2 (0x14027b229), (x0,y0) = (x,y) - ((i,j) - t) (0x14027b23e/0x14027b246)
        let t = Float(i + j) * g2
        let x0 = px - (Float(i) - t)
        let y0 = py - (Float(j) - t)

        // 두 번째 코너의 격자 오프셋 (0x14027b252 comiss + seta/setbe)
        let i1: Int, j1: Int
        if x0 > y0 { i1 = 1; j1 = 0 } else { i1 = 0; j1 = 1 }

        // (0x14027b284/0x14027b2af) x1 = x0 - i1 + G2, (0x14027b2c0/0x14027b2c9) x2 = x0 - 1 + 2·G2
        let x1 = x0 - Float(i1) + g2, y1 = y0 - Float(j1) + g2
        let x2 = x0 - 1 + g2x2,       y2 = y0 - 1 + g2x2

        // 8비트 랩(0x14027b2e8 movzx). perm 이 256 주기로 타일링돼 있어 인덱스를 512 표에
        // 그대로 넣어도 실물의 `& 0xff` 와 같다 — 최대 255 + 1 + 255 = 511.
        let ii = Int(clamping: i & 0xff), jj = Int(clamping: j & 0xff)

        // n0 (0x14027b2dd–0x14027b33d)
        var n0: Float = 0
        var t0 = 0.5 - x0 * x0 - y0 * y0
        if t0 >= 0 {
            t0 *= t0; t0 *= t0
            n0 = grad2(perm[ii + Int(clamping: perm[jj])], x0, y0) * t0
        }
        // n1 (0x14027b342–0x14027b3ca)
        var n1: Float = 0
        var t1 = 0.5 - x1 * x1 - y1 * y1
        if t1 >= 0 {
            t1 *= t1; t1 *= t1
            n1 = grad2(perm[ii + i1 + Int(clamping: perm[jj + j1])], x1, y1) * t1
        }
        // n2 (0x14027b3ce–0x14027b457)
        var n2: Float = 0
        var t2 = 0.5 - x2 * x2 - y2 * y2
        if t2 >= 0 {
            t2 *= t2; t2 *= t2
            n2 = grad2(perm[ii + 1 + Int(clamping: perm[jj + 1])], x2, y2) * t2
        }
        // (0x14027b46b/0x14027b488/0x14027b49c) — 합 순서까지 실물 그대로.
        return ((n1 + n0) + n2) * scale2
    }

    /// 3D 심플렉스 노이즈. 일반 입력에서는 치역 [-1, 1](실측 봉우리 ±0.977).
    /// **단, `y0 == z0 && x0 < y0` 동률에서는 실물의 코너 선택 결함 때문에 ±1.39 까지 벌어진다** —
    /// 파일 헤더의 "코너 선택" 절 참조. [-1, 1] 이 계약이면 호출부에서 클램프해라.
    /// 실물 `0x1400fc220`–`0x1400fd006`(SSE2) / `0x1400fd010`–`0x1400fdc41`(SSE4.1) 이식.
    public static func snoise3(_ x: Float, _ y: Float, _ z: Float) -> Float {
        let px = fold(x), py = fold(y), pz = fold(z)

        // s = ((y+z)+x)·F3 — 실물의 덧셈 순서(0x1400fc2c6/0x1400fc2ef, 0x1400fc2f8 mulps)
        let s = ((py + pz) + px) * f3
        let i = fastFloor(px + s)
        let j = fastFloor(py + s)
        let k = fastFloor(pz + s)

        let t = Float(i + j + k) * g3
        let x0 = px - (Float(i) - t)
        let y0 = py - (Float(j) - t)
        let z0 = pz - (Float(k) - t)

        // 코너 선택(0x1400fc517–0x1400fc6be). 실물은 4레인 SIMD 라 자바 원본의 if/else 사슬을
        // 분기 없는 마스크 곱/합으로 펼쳐 놨다. 비교 술어를 명령 단위로 옮긴다.
        let cmpA = y0 <= x0   // 0x1400fc517  cmpleps y0, x0
        let cmpB = z0 <= x0   // 0x1400fc51c  cmpleps z0, x0
        let cmpC = x0 < y0    // 0x1400fc521  cmpltps x0, y0
        let cmpD = x0 < z0    // 0x1400fc52d  cmpltps x0, z0
        let cmpE = y0 < z0    // 0x1400fc532  cmpltps y0, z0
        let cmpG = z0 <= y0   // 0x1400fc536  cmpleps z0, y0
        let cmpH = z0 < y0    // 0x1400fc590  cmpltps z0, y0  (j1 전용 — 동률에서 cmpG 와 갈린다)

        let i1 = (cmpA && cmpB) ? 1 : 0                                    // 0x1400fc54b/0x1400fc54f
        let j1 = (cmpC && cmpH) ? 1 : 0                                    // 0x1400fc594/0x1400fc598
        let k1 = (cmpD && cmpE) ? 1 : 0                                    // 0x1400fc5dd/0x1400fc5e5
        let i2 = ((cmpC && cmpB) || (cmpD && cmpA) || i1 == 1) ? 1 : 0     // 0x1400fc635/0x1400fc638
        let j2 = ((cmpE && cmpC) || (cmpG && cmpA) || j1 == 1) ? 1 : 0     // 0x1400fc674/0x1400fc67d
        let k2 = ((cmpG && cmpD) || (cmpE && cmpB) || k1 == 1) ? 1 : 0     // 0x1400fc6a7/0x1400fc6b4

        // x1 = x0 - i1 + G3 (0x1400fc73a), x2 = x0 - i2 + 2·G3 (0x1400fc76e), x3 = x0 - 1 + 3·G3
        let x1 = x0 - Float(i1) + g3, y1 = y0 - Float(j1) + g3, z1 = z0 - Float(k1) + g3
        let x2 = x0 - Float(i2) + g3x2, y2 = y0 - Float(j2) + g3x2, z2 = z0 - Float(k2) + g3x2
        let x3 = x0 - 1 + g3x3, y3 = y0 - 1 + g3x3, z3 = z0 - 1 + g3x3

        // gi = permMod12[ii + perm[jj + perm[kk]]] — 0x1400fc82f/0x1400fc9c7/0x1400fc9a1
        let ii = Int(clamping: i & 255), jj = Int(clamping: j & 255), kk = Int(clamping: k & 255)
        let gi0 = Int(clamping: permMod12[ii      + Int(clamping: perm[jj      + Int(clamping: perm[kk])])])
        let gi1 = Int(clamping: permMod12[ii + i1 + Int(clamping: perm[jj + j1 + Int(clamping: perm[kk + k1])])])
        let gi2 = Int(clamping: permMod12[ii + i2 + Int(clamping: perm[jj + j2 + Int(clamping: perm[kk + k2])])])
        let gi3 = Int(clamping: permMod12[ii + 1  + Int(clamping: perm[jj + 1  + Int(clamping: perm[kk + 1])])])

        let n0 = corner3(gi0, x0, y0, z0)
        let n1 = corner3(gi1, x1, y1, z1)
        let n2 = corner3(gi2, x2, y2, z2)
        let n3 = corner3(gi3, x3, y3, z3)
        return (((n0 + n1) + n2) + n3) * 32   // 0x1400fcfec  mulps [0x1404835d0]
    }

    // MARK: - 커널 내부(테스트에서 직접 찔러 본다)

    /// 실물 `0x14027b300`–`0x14027b338` 인라인 `grad2`.
    ///
    /// upstream(`simplexnoise1234.c`):
    /// ```c
    /// int h = hash & 7;                    // ← 실물은 & 0x3F
    /// float u = h<4 ? x : y;
    /// float v = h<4 ? y : x;
    /// return ((h&1)? -u : u) + ((h&2)? -2.0f*v : 2.0f*v);
    /// ```
    /// 실물은 `test al, 0x3C` 로 **비트 2..5** 를 본다. `hash & 7` 이었다면 `test al, 4` 였다.
    @inline(__always)
    static func grad2(_ hash: UInt8, _ x: Float, _ y: Float) -> Float {
        let swapped = (hash & 0x3C) != 0          // 0x14027b300  test al, 0x3c / jne
        var u = swapped ? y : x                   // 0x14027b304 / 0x14027b30a
        let vRaw = swapped ? x : y
        if hash & 1 != 0 { u = -u }               // 0x14027b311  test al,1 → xorps -0.0
        // 0x14027b31c  test al,2 → mulss -2.0 (0x1404929e0) : addss v,v
        let v = (hash & 2) != 0 ? -2 * vRaw : vRaw + vRaw
        return v + u                              // 0x14027b334  addss xmm4, xmm5
    }

    /// 3D 코너 기여분. `t = 0.6 - |p|²`, 음수면 0, 아니면 `t⁴ · dot(grad3[gi], p)`.
    /// 감쇠 0.6 은 `0x140483620`, `t<0 → 0` 는 `cmpltps`+`andnps`(`0x1400fcd7e`/`0x1400fcdec`).
    @inline(__always)
    static func corner3(_ gi: Int, _ x: Float, _ y: Float, _ z: Float) -> Float {
        var t = 0.6 - x * x - y * y - z * z
        if t < 0 { return 0 }
        t *= t
        return t * t * (grad3X[gi] * x + grad3Y[gi] * y + grad3Z[gi] * z)
    }

    // MARK: - 상수

    /// `F2 = 0.366025403f` — `0x1404926a4`, `mulss` @`0x14027b1a8`.
    static let f2: Float = 0.366025403
    /// `G2 = 0.211324865f` — `0x140492680`.
    static let g2: Float = 0.211324865
    /// `2·G2` — `0x1404926b4` (별도 상수로 박혀 있다).
    static let g2x2: Float = 0.42264974
    /// 2D 최종 스케일 — `0x1404928c8`. upstream 은 `40.0f`. 차이는 파일 헤더 주석 참조.
    static let scale2: Float = 45.23065185546875
    /// `F3 = 1/3` — `0x140483610`.
    static let f3: Float = 0.33333334
    /// `G3 = 1/6` — `0x140483600`.
    static let g3: Float = 0.16666667
    /// `2·G3 = 1/3` — `0x1404835e0`.
    static let g3x2: Float = 0.33333334
    /// `3·G3 = 0.5` — `0x140483650` (1/6 의 3배가 아니라 정확히 0.5 로 박혀 있다).
    static let g3x3: Float = 0.5

    /// 좌표 접기 한계. 실물은 `cvttss2si` 라 오버플로에서 `INT_MIN` 을 뱉고 넘어가지만
    /// Swift 의 `Int(Float)` 는 **트랩**한다. |v| > 10⁶ 이면 float32 격자 해상도가 이미
    /// 소진된 구간이라(ulp ≥ 0.0625) 접어도 시각적 차이가 없고, 대신 결정적·무크래시가 된다.
    /// `ParticleSimulator.valueNoise3` 의 `wrap` 과 같은 관례다.
    static let coordLimit: Float = 1_000_000

    // MARK: - 표(바이너리에서 그대로 덤프)

