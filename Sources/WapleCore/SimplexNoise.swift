    /// `cvttss2si` + 보정(`0x14027b1dd`–`0x14027b1f1`: 절단값이 원값보다 크면 1 뺀다).
    /// `fold` 가 정의역을 ±10⁶ 로 묶어 두므로 `Int(_:)` 가 트랩하지 않는다.
    @inline(__always)
    static func fastFloor(_ x: Float) -> Int {
        let i = Int(x)                 // 0 방향 절단
        return Float(i) > x ? i - 1 : i
    }

    /// 비유한 → 0, |v| > 10⁶ → 나머지로 접기. `coordLimit` 주석 참조.
    @inline(__always)
    static func fold(_ v: Float) -> Float {
        guard v.isFinite else { return 0 }
        return v.magnitude <= coordLimit ? v : v.truncatingRemainder(dividingBy: coordLimit)
    }
